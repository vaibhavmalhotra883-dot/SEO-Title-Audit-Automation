import requests
from bs4 import BeautifulSoup
import pandas as pd
from urllib.parse import urlparse, urljoin
import time
from collections import Counter
from google.colab import files

# --- CONFIGURATION ---
START_URL = "https://imtsinstitute.com"
MAX_PAGES = 150  # Aap is limit ko badha sakte hain

def get_detailed_audit(start_url, max_pages=100):
    domain = urlparse(start_url).netloc
    urls_to_visit = [start_url]
    visited_urls = set()
    raw_data = []

    print("🔍 Website crawling aur data collection shuru ho gaya hai...")

    # Phase 1: Crawling and Title Gathering
    while urls_to_visit and len(visited_urls) < max_pages:
        current_url = urls_to_visit.pop(0)
        if current_url in visited_urls:
            continue

        try:
            headers = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36'}
            response = requests.get(current_url, headers=headers, timeout=10)
            visited_urls.add(current_url)

            if 'text/html' not in response.headers.get('Content-Type', ''):
                continue

            soup = BeautifulSoup(response.text, 'html.parser')
            title_tag = soup.find('title')
            title = title_tag.string.strip() if title_tag else "Missing Title"

            raw_data.append({"URL": current_url, "Title": title})
            print(f"Collected [{len(raw_data)}]: {current_url}")

            for link in soup.find_all('a', href=True):
                full_url = urljoin(current_url, link['href']).split('#')[0]
                if urlparse(full_url).netloc == domain and full_url not in visited_urls:
                    if full_url not in urls_to_visit:
                        urls_to_visit.append(full_url)
            time.sleep(0.3)

        except Exception as e:
            visited_urls.add(current_url)

    # Title Counts duplicate nikalne ke liye
    all_titles = [d['Title'] for d in raw_data if d['Title'] != "Missing Title"]
    title_counts = Counter(all_titles)

    final_sheet_data = []

    # Phase 2: Applying requested custom sheet structure
    for data in raw_data:
        url = data['URL']
        title = data['Title']
        length = len(title)
        is_duplicate = title_counts[title] > 1 if title != "Missing Title" else False

        # Default rules baseline
        issue = "Perfect Title"
        solution = "No action required."
        guide = "Monitor organic CTR performance in Google Search Console."
        priority = "Low"
        impact = "Maintains stable current keyword rankings and visibility."

        # Audit conditions logic
        if title == "Missing Title":
            issue = "Missing Title Tag (Page has no title element)"
            solution = "Create and add a completely unique, descriptive title tag for this page."
            guide = "1. Open the page source or CMS manager.\n2. Create a new title (50-60 characters) using the primary keyword.\n3. Insert it inside the <head> tags as <title>Your Title</title>.\n4. Save and clear website cache."
            priority = "Critical"
            impact = "High: Google cannot index or understand what this page is about, resulting in poor or zero search visibility."

        elif is_duplicate:
            issue = f"Duplicate Title Tag (Shared with other internal pages) | Current: '{title}'"
            solution = "Rewrite this specific title to reflect the unique value or location/course of this page."
            guide = "1. Find all pages using this same title.\n2. Review the core content of this specific URL.\n3. Add distinct variations such as specific course codes, location, or formats (e.g., Online/Distance).\n4. Update the tag via CMS or HTML."
            priority = "High"
            impact = "High: Causes keyword cannibalization where Google gets confused about which internal page to rank, lowering rankings for all of them."

        elif length > 60:
            issue = f"Too Long Title Tag ({length} characters)"
            solution = f"Shorten the title to fit within the 50-60 character limit (approx 580px)."
            guide = f"1. Current Title is: '{title}'.\n2. Trim non-essential words or long phrases.\n3. Keep the main target keyword at the front.\n4. Move or abbreviate the brand identifier at the end."
            priority = "Medium"
            impact = "Medium: Google cuts off the title with '...' in search results, which looks unprofessional and drops your Click-Through Rate (CTR)."

        elif length < 30:
            issue = f"Too Short Title Tag ({length} characters)"
            solution = "Expand the title by integrating secondary keywords, target audience, or branding elements."
            guide = f"1. Current Title is: '{title}'.\n2. Add high-volume modifier keywords (e.g., 'Fees, Syllabus, Admission').\n3. Append the brand name '| IMTS Institute' if missing.\n4. Ensure total length reaches 45-60 characters."
            priority = "Low"
            impact = "Medium: Missing out on valuable keyword optimization opportunities, causing lower rankings for long-tail search queries."

        elif "IMTS" not in title:
            issue = "Missing Brand Name Identifier"
            solution = "Append the official brand suffix to the end of the title."
            guide = f"1. Edit current title: '{title}'.\n2. Add a separator and brand name at the tight right edge: ' | IMTS Institute'.\n3. Verify total character count stays under 60 characters."
            priority = "Low"
            impact = "Low: Reduces brand recognition, trust, and consistency across organic search results."

        final_sheet_data.append({
            "Affiliated Urls": url,
            "Issue Detected": issue,
            "Solution": solution,
            "Step by step Guide": guide,
            "Priority": priority,
            "Business Impact": impact
        })

    return final_sheet_data

# Process and execution
audit_data = get_detailed_audit(START_URL, max_pages=MAX_PAGES)
df = pd.DataFrame(audit_data)

# Exporting formatted dataset
output_filename = "IMTS_Custom_Title_Audit_Sheet.xlsx"
df.to_excel(output_filename, index=False)

print(f"\n✅ Audit complete! Aapki strict requirements ke mutabik sheet ready hai.")
print(f"📥 File download ho rahi hai: {output_filename}")

files.download(output_filename)